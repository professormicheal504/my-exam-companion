const express = require('express');
const cors = require('cors');
require('dotenv').config({ path: './supabase/.env.local' });

const app = express();
app.use(cors());
app.use(express.json());

// Helper functions (same as edge function)
function base64ToUtf8(b64) {
  const clean = b64.replace(/\s/g, '');
  return Buffer.from(clean, 'base64').toString('utf8');
}

function utf8ToBase64(str) {
  return Buffer.from(str, 'utf8').toString('base64');
}

function extractQuestions(data) {
  if (Array.isArray(data)) return data;
  if (data && typeof data === 'object') {
    if (Array.isArray(data.questions)) return data.questions;
    return Object.values(data).filter(v => v && typeof v === 'object' && !Array.isArray(v));
  }
  return [];
}

app.post('/functions/v1/explain-question', async (req, res) => {
  try {
    const { repoPath, questionId, questionText, options, correctAnswer, isGridIn } = req.body;

    if (!repoPath || !questionText) {
      return res.status(400).json({ error: 'repoPath and questionText are required.' });
    }

    const mistralKey = process.env.MISTRAL_API_KEY;
    const githubToken = process.env.GITHUB_TOKEN;
    const githubRepo = process.env.GITHUB_REPO;

    if (!mistralKey || !githubToken || !githubRepo) {
      return res.status(500).json({ error: 'Server configuration missing required API keys.' });
    }

    // 1. Generate explanation with Mistral API
    let optionsText = "";
    if (isGridIn) {
      optionsText = "This is a fill-in-the-blank (Grid-In) question.";
    } else if (Array.isArray(options) && options.length > 0) {
      optionsText = options.map((opt, i) => `${['A','B','C','D','E'][i] || i}. ${opt}`).join("\n");
    }

    const prompt = `Question: ${questionText}\n\nOptions:\n${optionsText}\n\nCorrect Answer: ${correctAnswer}`;
    
    console.log(`[AI] Generating explanation for Question ${questionId}...`);
    
    const mistralRes = await fetch("https://api.mistral.ai/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Authorization": `Bearer ${mistralKey}`
      },
      body: JSON.stringify({
        model: "mistral-small-latest",
        messages: [
          { role: "system", content: "You are a helpful, expert tutor. Briefly and clearly explain why the correct answer is correct for the given question. Do not include introductory filler. Output ONLY the raw explanation text. You may use <b> and <i> for emphasis. Do not output markdown." },
          { role: "user", content: prompt }
        ],
        max_tokens: 500,
        temperature: 0.3,
      })
    });

    if (!mistralRes.ok) throw new Error(`Mistral API error: ${mistralRes.status}`);
    const mistralData = await mistralRes.json();
    
    if (!mistralData.choices || mistralData.choices.length === 0) {
      return res.status(400).json({ error: 'Mistral returned no completion choices.' });
    }
    
    const rawExplanation = (mistralData.choices[0].message?.content || '').trim();
    const safeExplanation = rawExplanation
      .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')
      .replace(/&lt;(\/?(b|i))&gt;/gi, '<$1>');

    const explanation = `<p>${safeExplanation}</p><span class="ai-generated-tag">✨ This was written by AI (Generated by a student)</span>`;

    // 2. Fetch the existing JSON file from GitHub
    console.log(`[GitHub] Fetching ${repoPath}...`);
    const cleanRepoPath = repoPath.trim().replace(/^\//, '');
    const githubApiUrl = `https://api.github.com/repos/${githubRepo}/contents/${encodeURIComponent(cleanRepoPath).replace(/%2F/g, '/')}`;
    
    const ghRes = await fetch(githubApiUrl, {
      headers: {
        "Authorization": `Bearer ${githubToken}`,
        "Accept": "application/vnd.github.v3+json",
        "User-Agent": "MyExamCompanion/1.0"
      }
    });

    if (!ghRes.ok) {
      return res.json({ explanation, savedToGithub: false, githubError: `Fetch failed: ${ghRes.status}` });
    }

    const ghData = await ghRes.json();
    let examData;
    try {
      examData = JSON.parse(base64ToUtf8(ghData.content));
    } catch (parseErr) {
      return res.json({ explanation, savedToGithub: false, githubError: 'JSON parse failed' });
    }

    // 3. Find the question and update it
    const rawQuestions = extractQuestions(examData);
    let found = false;
    
    for (let i = 0; i < rawQuestions.length; i++) {
      const q = rawQuestions[i];
      const currentQId = String(q.question_id || (i + 1));
      if (currentQId === String(questionId)) {
        if (!q.deep_analysis || typeof q.deep_analysis !== 'object') q.deep_analysis = {};
        q.deep_analysis.explanation = explanation;
        q.explanation = explanation;
        found = true;
        break;
      }
    }

    if (!found) {
      return res.json({ explanation, savedToGithub: false, githubError: 'Question ID not found in file' });
    }

    // 4. Encode and Commit back to GitHub
    console.log(`[GitHub] Committing update for Question ${questionId}...`);
    const updatedJsonStr = JSON.stringify(examData, null, 2);
    const encodedContent = utf8ToBase64(updatedJsonStr);

    const updateRes = await fetch(githubApiUrl, {
      method: "PUT",
      headers: {
        "Authorization": `Bearer ${githubToken}`,
        "Accept": "application/vnd.github.v3+json",
        "Content-Type": "application/json",
        "User-Agent": "MyExamCompanion/1.0"
      },
      body: JSON.stringify({
        message: `feat(ai): add explanation for question ${questionId} [bot]`,
        content: encodedContent,
        sha: ghData.sha,
        committer: { name: "MyExamCompanion Bot", email: "bot@myexamcompanion.app" }
      })
    });

    if (!updateRes.ok) {
      return res.json({ explanation, savedToGithub: false, githubError: `Commit failed: ${updateRes.status}` });
    }

    console.log(`✅ Success! Question ${questionId} updated on GitHub.`);
    return res.json({ explanation, savedToGithub: true });

  } catch (error) {
    console.error("Local server error:", error);
    res.status(500).json({ error: error.message });
  }
});
app.post('/functions/v1/chat-agent', async (req, res) => {
  try {
    const { messages, examContext } = req.body;
    const mistralKey = process.env.MISTRAL_API_KEY;

    if (!mistralKey) {
      return res.status(500).json({ error: 'Missing Mistral API Key.' });
    }

    const systemPrompt = `You are a premium AI Study Agent (like Claude) for students taking JAMB, WAEC, and NECO exams. You are highly intelligent, Socratic, and engaging. You never just give the answer—you guide the student to understand it. Keep your tone encouraging and elite. 
Use Markdown for rich formatting (tables, bold text, lists).
Here is the context about the student's recent exam performance:
${examContext || 'No recent exam data available.'}`;

    const apiMessages = [
      { role: "system", content: systemPrompt },
      ...(messages || [])
    ];

    const mistralRes = await fetch("https://api.mistral.ai/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Authorization": `Bearer ${mistralKey}`
      },
      body: JSON.stringify({
        model: "mistral-small-latest",
        messages: apiMessages,
        max_tokens: 1000,
        temperature: 0.5,
      })
    });

    if (!mistralRes.ok) throw new Error(`Mistral API error: ${mistralRes.status}`);
    const mistralData = await mistralRes.json();
    
    if (!mistralData.choices || mistralData.choices.length === 0) {
      return res.status(400).json({ error: 'Mistral returned no completion choices.' });
    }
    
    res.json({ text: mistralData.choices[0].message?.content || '' });
  } catch (error) {
    console.error("Local server error (chat):", error);
    res.status(500).json({ error: error.message });
  }
});
